// a[i] - строка, бит c - столбец c (m <= 64, иначе bitset). Возвращает ранг, O(n * m)
// После: в опорном столбце строки i < r единица только в ней, это её младший бит
int gauss(int n, int m, ulong *a) {
    int r = 0;
    for (int c = 0; c < m && r < n; ++c) {
        int i = r;
        while (i < n && !(a[i] >> c & 1))
            ++i;
        if (i == n)
            continue;
        swap(a[r], a[i]);
        for (i = 0; i < n; ++i)
            if (i != r && a[i] >> c & 1)
                a[i] ^= a[r];
        ++r;
    }
    return r;
}
